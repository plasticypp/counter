/** Entry point: Dispatch Tools -> Print Test Report for Selected Invoice Column. */
function printTestReportForActiveInvoiceColumn() {
  var ui = SpreadsheetApp.getUi();
  // getActiveSpreadsheet, NOT getSpreadsheet_(). getSpreadsheet_ returns openById() whenever
  // the SPREADSHEET_ID script property is cached, and a by-ID handle carries no cursor — so
  // getActiveCell() on it falls back to A1 regardless of what the user clicked. That is why
  // the invoice number read as "Machine" (the column A header) and why every row matched:
  // column A is Machine, which holds a positive number on all 42 rows.
  // The SPEC print has always used getActiveSpreadsheet() here, which is why it worked.
  var ss = SpreadsheetApp.getActiveSpreadsheet();
  if (!ss) { ui.alert('Open this from the Dispatch spreadsheet.'); return; }
  var sheet = ss.getSheetByName('Dispatch');
  if (!sheet) { ui.alert('No sheet named "Dispatch" found.'); return; }

  var cell = sheet.getActiveCell();
  // Dispatch has a SINGLE header row, and an invoice column carries its invoice number in that
  // same row — so the label row is where the invoice number lives.
  //
  // findInvoiceRow_ is named for an older two-row layout and returns the row ABOVE the headers,
  // which is 0 here. Every caller in this project uses it only as `findInvoiceRow_() + 1` to
  // get the label row; none treats the bare value as a row. Deriving the invoice row from it
  // directly produced row 0 and an impossible-to-satisfy error.
  var labelRow = findInvoiceRow_(sheet) + 1;
  // getDisplayValue, not getValue: the invoice cell may be a number or a date underneath, and
  // getValue would hand back 243 for a cell reading "00243", or a Date object for "26-27".
  // The invoice number is an identifier — what the planner sees in the cell IS the value.
  var col = cell.getColumn();
  var invoiceCell = sheet.getRange(labelRow, col);
  var invoiceNo = String(invoiceCell.getDisplayValue() || '').trim();
  if (!invoiceNo) {
    ui.alert('Column ' + invoiceCell.getA1Notation().replace(/\d+$/, '') +
      ' has no invoice number in row ' + labelRow + '.\n\n' +
      'Select a cell in an invoice column first. If you selected a RANGE, the column used is ' +
      'the one holding the active cell, which may not be the one you meant.');
    return;
  }

  // Confirm WHICH column and WHICH invoice before generating anything. The active cell of a
  // multi-cell selection is not always the column the user thinks they picked, and a wrong
  // column silently produces a correct-looking report against the wrong invoice.
  var confirm = ui.alert('Generate test reports?',
    'Invoice: ' + invoiceNo + '\n' +
    'Column: ' + invoiceCell.getA1Notation().replace(/\d+$/, '') + ' (row ' + labelRow + ')\n\n' +
    'Reports will be generated for every row with a quantity in this column.',
    ui.ButtonSet.OK_CANCEL);
  if (confirm !== ui.Button.OK) return;

  var result = generateTestReportsForInvoice_(invoiceNo, col);
  showTestReportDialog_(invoiceNo, result);
}

