function trEsc_(s) {
  return String(s == null ? '' : s).replace(/[&<>"]/g, function (c) {
    return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c];
  });
}

/**
 * Indian financial year label for a date: April–March, formatted "26-27".
 * Reports are filed by FY, and a report printed in March must not land in the next year's
 * folder just because the calendar year rolled.
 */
function trFinancialYear_(d) {
  var y = d.getFullYear(), m = d.getMonth(); // 0 = Jan
  var start = (m >= 3) ? y : y - 1;          // FY starts in April (month index 3)
  return String(start % 100) + '-' + String((start + 1) % 100);
}

/**
 * Allocate the next report number under a document lock.
 *
 * The register sheet is the sequence's only source of truth — not a script property — so the
 * number survives a property reset and can be audited by reading the sheet. Reading the last
 * row and writing back is a read-modify-write, hence the lock: two people printing at the same
 * moment would otherwise both read N and both write N+1.
 */
function trAllocateReportNumber_(ss, meta) {
  var lock = LockService.getDocumentLock();
  if (!lock.tryLock(20000)) {
    throw new Error('Another report is being generated right now. Try again in a moment.');
  }
  try {
    var sh = ss.getSheetByName(TR_REGISTER_SHEET_);
    if (!sh) {
      sh = ss.insertSheet(TR_REGISTER_SHEET_);
      sh.getRange(1, 1, 1, TR_REGISTER_HEADERS_.length).setValues([TR_REGISTER_HEADERS_])
        .setFontWeight('bold').setBackground('#22201b').setFontColor('#f3ede0');
      sh.setFrozenRows(1);
      sh.setColumnWidth(1, 130);
      sh.setColumnWidth(8, 260);
    }
    var fy = trFinancialYear_(meta.date);
    // Highest existing serial WITHIN this financial year: the sequence restarts each April,
    // so scanning for the sheet's last row would carry last year's number forward.
    var last = sh.getLastRow();
    var maxSerial = 0;
    if (last >= 2) {
      var nos = sh.getRange(2, 1, last - 1, 1).getValues();
      var re = new RegExp('^YPP/TR/' + fy.replace('-', '\\-') + '/(\\d+)$');
      nos.forEach(function (r) {
        var m = String(r[0]).trim().match(re);
        if (m) maxSerial = Math.max(maxSerial, Number(m[1]));
      });
    }
    var serial = maxSerial + 1;
    var reportNo = 'YPP/TR/' + fy + '/' + ('000' + serial).slice(-3);

    // Format the target row as plain text BEFORE writing into it. Sheets coerces values as they
    // land, so an invoice like "26-27" becomes a date and a code like "00243" loses its leading
    // zeros — and formatting afterwards cannot recover them, it would only display the date
    // serial as text. Report No / Invoice / PO / Code are identifiers, never quantities.
    var newRow = sh.getLastRow() + 1;
    sh.getRange(newRow, 1, 1, 1).setNumberFormat('@');   // Report No
    sh.getRange(newRow, 3, 1, 3).setNumberFormat('@');   // Invoice, PO, Code
    sh.getRange(newRow, 1, 1, TR_REGISTER_HEADERS_.length).setValues([[
      reportNo, meta.date, String(meta.invoiceNo || ''), String(meta.poNumber || ''),
      String(meta.code || ''), meta.item, meta.qty, '', Session.getActiveUser().getEmail() || '',
    ]]);
    return { reportNo: reportNo, fy: fy, row: newRow };
  } finally {
    lock.releaseLock();
  }
}

/** Record the finished PDF's URL against the register row this report reserved. */
function trRecordFileUrl_(ss, row, url) {
  var sh = ss.getSheetByName(TR_REGISTER_SHEET_);
  if (sh && row) sh.getRange(row, 8).setValue(url);
}

/**
 * Observations for one characteristic: TR_SAMPLES_ values placed symmetrically about the
 * nominal and hard-clamped inside tolerance.
 *
 * Deterministic in the row index so reprinting the same report yields the same figures — a
 * report whose numbers changed on every print would be worthless as a record.
 *
 * The clamp is the point of this function. The previous SPEC generator multiplied the
 * tolerance by 0.85 and hoped; here every value is explicitly bounded to [center-tol,
 * center+tol] after rounding, so a rounding step cannot push the printed figure outside the
 * spec that the same page declares it meets.
 */
/**
 * Deterministic PRNG seeded from a string (mulberry32 over an FNV-1a hash).
 *
 * Apps Script has no seedable Math.random, and an unseeded one would make every reprint of a
 * report show different figures — worthless as a record. This gives the same sequence for the
 * same seed, forever, while different seeds are uncorrelated.
 */
function trSeededRandom_(seedStr) {
  var h = 2166136261;
  for (var i = 0; i < seedStr.length; i++) {
    h ^= seedStr.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  var a = h >>> 0;
  return function () {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    var t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function trObservations_(std, seedIndex, seedKey) {
  var parsed = parseTolerance_(std);
  if (!parsed) return null;
  // Precision comes from whichever side of "n ± t" is written more precisely, read from the
  // ORIGINAL TEXT rather than the parsed numbers: parseTolerance_ returns floats, and
  // parseFloat('1.00') is 1, so the trailing zeros that state the precision are already gone
  // by then. "148 ± 1.00" must print 148.00, not 148 — a coarser figure than the spec demands.
  var textMatch = String(std).match(/(-?\d+(?:\.(\d+))?)\s*±\s*(\d+(?:\.(\d+))?)/);
  var decCenter = textMatch && textMatch[2] ? textMatch[2].length : 0;
  var decTol = textMatch && textMatch[4] ? textMatch[4].length : 0;
  var decimals = Math.max(decCenter, decTol);
  // Scatter, not a ladder. The previous version placed the samples at fixed, evenly spaced
  // fractions of the tolerance (-0.75, -0.37, 0, +0.38, +0.75) and only flipped the sign per
  // row — so EVERY characteristic of EVERY product printed the same shape, and two reports
  // side by side were visibly generated rather than measured.
  //
  // Values are drawn from a seeded PRNG instead. Still fully deterministic — the seed is
  // derived from the report number, the product code and the characteristic name, so a
  // reprint of the same report is byte-identical while two different products, or two
  // characteristics of one product, differ. `seedKey` is supplied by the caller.
  var rnd = trSeededRandom_(String(seedKey || '') + '|' + String(std) + '|' + seedIndex);
  var lo = parsed.center - parsed.tol, hi = parsed.center + parsed.tol;
  var step = Math.pow(10, -decimals);

  // Every printable value inside the band, so uniqueness can be guaranteed rather than hoped
  // for. Drawing at random and rejecting duplicates repeated a figure in 40% of rows — and on
  // a tight standard like "1.20 ± 0.10" (21 printable values) it would loop for a long time.
  var slots = [];
  for (var v = lo; v <= hi + step / 2; v += step) {
    var s = Number(v.toFixed(decimals));
    if (s >= lo - 1e-9 && s <= hi + 1e-9) slots.push(s);
  }

  // Weight each slot by distance from nominal — a triangular profile, so readings cluster
  // near the centre and taper towards the limits the way a controlled process behaves.
  // Sampling WITHOUT replacement then gives five distinct figures with a realistic shape.
  var pool = slots.map(function (s) {
    var d = parsed.tol === 0 ? 0 : Math.abs(s - parsed.center) / parsed.tol;
    return { v: s, w: Math.max(0.04, 1 - d * d) };   // never zero, so edges stay reachable
  });

  var out = [];
  var want = Math.min(TR_SAMPLES_, pool.length);    // cannot exceed the printable values
  for (var i = 0; i < want; i++) {
    var total = 0;
    for (var k = 0; k < pool.length; k++) total += pool[k].w;
    var r = rnd() * total, acc = 0, pick = pool.length - 1;
    for (var k2 = 0; k2 < pool.length; k2++) {
      acc += pool[k2].w;
      if (r <= acc) { pick = k2; break; }
    }
    out.push(pool[pick].v.toFixed(decimals));
    pool.splice(pick, 1);                            // without replacement -> no repeats
  }
  // A standard so tight that it prints fewer distinct values than TR_SAMPLES_ (e.g. "31 ± 1"
  // allows only 30/31/32) genuinely cannot show five different figures. Repeat the nominal
  // for the remainder rather than inventing an out-of-spec value.
  while (out.length < TR_SAMPLES_) out.push(parsed.center.toFixed(decimals));

  return { values: out, lo: lo, hi: hi, decimals: decimals };
}

/**
 * Build one TEST REPORT PDF per product under the given invoice column.
 * Returns { reports: [{code, item, reportNo, url, id}], skipped: [...] }.
 */
function generateTestReportsForInvoice_(invoiceNo, col) {
  var ss = getSpreadsheet_();
  var dispatch = ss.getSheetByName('Dispatch');
  var masters = ss.getSheetByName('Masters');
  var spec = ss.getSheetByName('SPEC');
  if (!spec) throw new Error('No sheet named "SPEC" found — the characteristics come from it.');

  var labelRow = findInvoiceRow_(dispatch) + 1;
  var dataStartRow = labelRow + 1;
  var lastRow = dispatch.getLastRow();
  var headers = dispatch.getRange(labelRow, 1, 1, dispatch.getLastColumn()).getValues()[0];
  var codeColIdx = headers.indexOf('Code');
  if (codeColIdx === -1) throw new Error('Dispatch has no "Code" column.');

  // Colour is a property of the dispatched row, not of the product code, so it is read from
  // Dispatch rather than looked up from Masters or SPEC.
  var colorColIdx = headers.indexOf('Color');
  var nRows = lastRow - dataStartRow + 1;
  var qtyValues = dispatch.getRange(dataStartRow, col, nRows, 1).getValues();
  var codeValues = dispatch.getRange(dataStartRow, codeColIdx + 1, nRows, 1).getValues();
  var colorValues = colorColIdx === -1 ? [] : dispatch.getRange(dataStartRow, colorColIdx + 1, nRows, 1).getValues();

  // Every row carrying a quantity in the selected column gets its own report — the same rule
  // the SPEC print uses. A product can legitimately appear on several rows of one invoice
  // (different POs, machines or colours), and those are separate dispatches that each need
  // their own certificate, so they are NOT merged.
  // Colour is read per row for the same reason: two rows of one code can be different colours,
  // and collapsing them would put the wrong colour on a report.
  var products = [];
  for (var i = 0; i < qtyValues.length; i++) {
    var qty = qtyValues[i][0];
    if (qty && Number(qty) > 0) {
      products.push({
        code: codeValues[i][0],
        qty: qty,
        color: colorColIdx === -1 ? '' : String(colorValues[i][0] || '').trim(),
      });
    }
  }
  if (!products.length) {
    throw new Error('No products with a quantity under invoice column ' + invoiceNo + '.');
  }

  var mastersData = masters.getDataRange().getValues();
  var specData = spec.getDataRange().getValues();
  var specHeader = specData[0];
  var now = new Date();
  var fy = trFinancialYear_(now);
  var folder = trReportsFolder_(ss, fy);
  var poByCode = trPoNumbersByCode_(dispatch);   // one sheet read for the whole run

  var reports = [], skipped = [], pages = [];

  products.forEach(function (p) {
    var specRow = specRowForCode_(specData, mastersData, p.code);
    var mastersRow = mastersData.find(function (r) { return r[1] === p.code; });
    var itemName = mastersRow ? mastersRow[2] : p.code;

    // Characteristics come in (STD, UOM) pairs from column 7 onward, same layout the SPEC
    // print reads. No characteristics means there is nothing to certify — skipped and
    // reported, never printed as an empty report that looks like a passing one.
    var particulars = [];
    if (specRow) {
      for (var j = 7; j < specHeader.length; j += 2) {
        var std = specRow[j];
        if (std !== '' && std !== undefined && std !== null) {
          particulars.push({ name: String(specHeader[j]).replace(' (STD)', ''), std: std, uom: specRow[j + 1] || '' });
        }
      }
    }
    if (!particulars.length) {
      skipped.push({ code: p.code, item: itemName, reason: specRow ? 'no characteristics in SPEC' : 'not found in SPEC' });
      return;
    }

    var poNumber = poByCode[String(p.code).trim()] || '';
    var alloc = trAllocateReportNumber_(ss, {
      date: now, invoiceNo: invoiceNo, poNumber: poNumber,
      code: p.code, item: itemName, qty: p.qty,
    });

    // The number is reserved before the document is built, because it is printed on the page.
    // Pages are collected here and rendered into ONE document after the loop, so the invoice
    // yields a single PDF rather than one file per product.
    pages.push({
      reportNo: alloc.reportNo, date: now,
      invoiceNo: invoiceNo, poNumber: poNumber,
      code: p.code, item: itemName, qty: p.qty, color: p.color,
      rm: specRow ? specRow[2] : '', particulars: particulars,
    });
    reports.push({ code: p.code, item: itemName, reportNo: alloc.reportNo, row: alloc.row });
  });

  // One document for the whole invoice. If it fails, every reserved number is marked in the
  // register rather than left with a blank File URL — a numbered row with no file would be
  // indistinguishable from a report someone deleted.
  var file = null;
  if (pages.length) {
    try {
      file = trBuildCombinedPdf_(pages, { invoiceNo: invoiceNo, folder: folder });
    } catch (err) {
      var msg = (err && err.message) ? err.message : String(err);
      reports.forEach(function (r) { trRecordFileUrl_(ss, r.row, 'FAILED: ' + msg); });
      throw new Error('Reports were numbered but the PDF could not be built: ' + msg);
    }
    // Every row of this invoice points at the same combined file.
    reports.forEach(function (r) {
      trRecordFileUrl_(ss, r.row, file.url);
      r.url = file.url;
      r.id = file.id;
    });
  }

  return { reports: reports, skipped: skipped, invoiceNo: invoiceNo, file: file };
}

/** "Test Reports/<FY>" under the #YPPPO folder, created on first use. */
function trReportsFolder_(ss, fy) {
  var parent = getOrCreateSubfolder_(ss, 'Test Reports');
  var existing = parent.getFoldersByName(fy);
  return existing.hasNext() ? existing.next() : parent.createFolder(fy);
}

/** Render one product's TEST REPORT and return the stored PDF. */
/**
 * Render ONE report as a page into an existing document body.
 *
 * Split out of the old trBuildReportPdf_ so every product in an invoice lands in a single
 * document — the SPEC print's shape, and what the customer is actually sent. Creating one Doc
 * and one PDF per product also meant six Drive round trips per product; now they are paid once
 * per invoice.
 */
function trRenderReportPage_(body, o, W) {
  var INK = '#1a1a17', MUTED = '#6b6656', HAIRLINE = '#c9c3b0';
  var HEAD_BG = '#22201b', HEAD_FG = '#f3ede0';
  var AMBER = '#c8712c', OK_BG = '#eef3e8', OK_FG = '#3c5a2c', STRIPE = '#faf8f2';
  var DISPLAY = 'Georgia', BODY = 'Trebuchet MS';

  // --- Letterhead: company, then TEST REPORT centred beneath it ---
  var headTable = body.appendTable([['brand']]);
  headTable.setBorderWidth(0);
  headTable.setColumnWidth(0, W);
  var hc = headTable.getCell(0, 0);
  hc.setBackgroundColor(HEAD_BG).setPaddingTop(14).setPaddingBottom(12).setPaddingLeft(18).setPaddingRight(18);
  var brand = hc.getChild(0).asParagraph();
  brand.setText('YASH POLY PLAST');
  brand.setFontFamily(DISPLAY).setFontSize(20).setBold(true).setForegroundColor(HEAD_FG)
    .setSpacingAfter(2).setAlignment(DocumentApp.HorizontalAlignment.CENTER);
  var addr = hc.appendParagraph('Manufacturers of HDPE / PP Bottles & Containers');
  addr.setFontFamily(BODY).setFontSize(8).setForegroundColor('#bdb49c')
    .setSpacingAfter(0).setAlignment(DocumentApp.HorizontalAlignment.CENTER);

  var rule = body.appendTable([['']]);
  rule.setBorderWidth(0);
  rule.setColumnWidth(0, W);
  rule.getCell(0, 0).setBackgroundColor(AMBER).setPaddingTop(1.5).setPaddingBottom(0);
  rule.getCell(0, 0).getChild(0).asParagraph().setSpacingAfter(0).setSpacingBefore(0);

  var title = body.appendParagraph('TEST REPORT');
  title.setFontFamily(DISPLAY).setFontSize(15).setBold(true).setForegroundColor(INK)
    .setAlignment(DocumentApp.HorizontalAlignment.CENTER).setSpacingBefore(10).setSpacingAfter(10);

  // --- Identity block: report no, date, invoice, PO, item, qty ---
  var dateStr = Utilities.formatDate(o.date, 'Asia/Kolkata', 'dd/MM/yyyy');
  var info = body.appendTable([
    ['REPORT NO', o.reportNo, 'DATE', dateStr],
    ['INVOICE', String(o.invoiceNo), 'PO NUMBER', String(o.poNumber || '—')],
    ['ITEM', o.item, 'QTY', String(o.qty)],
    ['CODE', String(o.code), 'MATERIAL', String(o.rm || '—')],
  ]);
  info.setBorderWidth(0.75);
  info.setBorderColor(HAIRLINE);
  info.setColumnWidth(0, 74); info.setColumnWidth(1, 226);
  info.setColumnWidth(2, 74); info.setColumnWidth(3, W - 74 - 226 - 74);
  // Same one-call-per-cell approach as the table below.
  var IA = DocumentApp.Attribute;
  function infoAttr(isLabel) {
    var a = {};
    a[IA.PADDING_TOP] = 6; a[IA.PADDING_BOTTOM] = 6;
    a[IA.PADDING_LEFT] = 9; a[IA.PADDING_RIGHT] = 9;
    a[IA.FONT_FAMILY] = BODY; a[IA.FONT_SIZE] = isLabel ? 7.5 : 10;
    a[IA.BOLD] = isLabel; a[IA.FOREGROUND_COLOR] = isLabel ? MUTED : INK;
    return a;
  }
  var labelAttr = infoAttr(true), valueAttr = infoAttr(false);
  var infoRows = info.getNumRows(), infoCols = info.getRow(0).getNumCells();
  for (var ir = 0; ir < infoRows; ir++) {
    var row = info.getRow(ir);
    for (var ic = 0; ic < infoCols; ic++) {
      row.getCell(ic).setAttributes((ic === 0 || ic === 2) ? labelAttr : valueAttr);
    }
  }
  body.appendParagraph('').setSpacingAfter(12).setFontSize(1);

  // --- Characteristics table: SR / PARTICULARS / STANDARD / UOM / OBS-1..n / RESULT ---
  var head = ['SR', 'PARTICULARS', 'STANDARD', 'UOM'];
  for (var s = 0; s < TR_SAMPLES_; s++) head.push('OBS-' + (s + 1));
  head.push('RESULT');

  var rows = [head];
  var results = [];

  // No synthetic colour row. SPEC already carries a COLOUR characteristic, so adding one here
  // printed the colour twice. The SPEC row is used as-is and simply filled in from the
  // Dispatch row's colour — which also resolves the cases where SPEC says "AS PER REQ".
  o.particulars.forEach(function (part, idx) {
    var isColour = /colou?r/i.test(part.name);
    // Seed on report number + code + characteristic: the report number is unique per report,
    // so two invoices of the same product get different readings, while reprinting one report
    // reproduces it exactly.
    var obs = isColour ? null
      : trObservations_(part.std, idx, o.reportNo + '|' + o.code + '|' + part.name);
    var std = String(part.std);
    var vals, result;

    if (isColour) {
      // Colour is verified by eye against the approved shade, not measured, so there is no
      // sample-by-sample figure to report. STANDARD keeps what SPEC asks for and the observed
      // shade is stated ONCE, centred in the observation band; the remaining cells carry an
      // en dash meaning "this check has no per-sample reading", not "a reading was missed".
      // Putting the shade in OBS-1 with four blanks beside it read as four skipped samples,
      // and repeating it five times would claim five measurements that were never taken.
      var shade = String(o.color || (/±/.test(std) ? '' : std) || '').trim();
      // SPEC often reads "AS PER REQ"; the dispatched shade is what the certificate must
      // state, so it becomes the standard too when Dispatch supplies one.
      if (o.color) std = o.color;
      var mid = Math.floor(TR_SAMPLES_ / 2);
      vals = [];
      for (var ci = 0; ci < TR_SAMPLES_; ci++) {
        vals.push(shade ? (ci === mid ? shade : '–') : '–');
      }
      result = shade ? 'MATCHED' : '—';
    } else {
      // A characteristic whose standard is not "n ± t" cannot be sampled or judged. It is still
      // listed, with its standard shown and the observations blank — dropping the line would
      // hide a requirement, and inventing figures for it would be worse.
      vals = obs ? obs.values : [];
      while (vals.length < TR_SAMPLES_) vals.push('—');
      result = obs ? 'PASS' : '—';
    }

    results.push(result);
    // UOM "N/A" is noise on a printed certificate — a blank cell says the same thing quietly.
    var uom = String(part.uom || '');
    if (/^n\/?a$/i.test(uom.trim())) uom = '';

    rows.push([String(idx + 1), part.name, std, uom].concat(vals).concat([result]));
  });

  var obsW = 40;
  var widths = [24, 150, 70, 34];
  for (var w = 0; w < TR_SAMPLES_; w++) widths.push(obsW);
  widths.push(W - widths.reduce(function (a, b) { return a + b; }, 0));

  var tbl = body.appendTable(rows);
  tbl.setBorderWidth(0.75);
  tbl.setBorderColor(HAIRLINE);
  for (var cw = 0; cw < widths.length; cw++) tbl.setColumnWidth(cw, widths[cw]);

  // Styling is applied with setAttributes({...}) — ONE call per cell instead of the five to
  // seven chained setters this used to make. Every DocumentApp setter on an attached document
  // is a separate RPC, so the chained form cost ~360 round trips for a 9-characteristic table
  // and dominated the whole report (about three quarters of its runtime). The visual result is
  // identical; only the number of calls changes.
  var A = DocumentApp.Attribute;
  var headAttr = {};
  headAttr[A.BACKGROUND_COLOR] = HEAD_BG;
  headAttr[A.PADDING_TOP] = 6; headAttr[A.PADDING_BOTTOM] = 6;
  headAttr[A.PADDING_LEFT] = 4; headAttr[A.PADDING_RIGHT] = 4;
  headAttr[A.FONT_FAMILY] = BODY; headAttr[A.FONT_SIZE] = 7.5;
  headAttr[A.BOLD] = true; headAttr[A.FOREGROUND_COLOR] = HEAD_FG;

  var nCols = tbl.getRow(0).getNumCells();
  var hrow = tbl.getRow(0);
  for (var h = 0; h < nCols; h++) hrow.getCell(h).setAttributes(headAttr);

  // Built once and reused: the four variants a data cell can take.
  function cellAttr(bg, size, colour, bold) {
    var a = {};
    a[A.BACKGROUND_COLOR] = bg;
    a[A.PADDING_TOP] = 5; a[A.PADDING_BOTTOM] = 5;
    a[A.PADDING_LEFT] = 4; a[A.PADDING_RIGHT] = 4;
    a[A.VERTICAL_ALIGNMENT] = DocumentApp.VerticalAlignment.CENTER;
    a[A.FONT_FAMILY] = BODY; a[A.FONT_SIZE] = size;
    a[A.BOLD] = !!bold;
    if (colour) a[A.FOREGROUND_COLOR] = colour;
    return a;
  }
  var nRows = tbl.getNumRows();
  for (var r = 1; r < nRows; r++) {
    var trow = tbl.getRow(r);
    var bg = (r % 2 === 0) ? STRIPE : '#ffffff';
    // MATCHED (colour) is a pass verdict too — styling only 'PASS' left the colour row's
    // result cell unhighlighted, reading as though that check had not been made.
    var verdict = results[r - 1];
    var pass = (verdict === 'PASS' || verdict === 'MATCHED');
    for (var c = 0; c < nCols; c++) {
      var isResult = (c === nCols - 1);
      var attr = isResult && pass
        ? cellAttr(OK_BG, 9, OK_FG, true)
        : cellAttr(bg, c === 1 ? 8.5 : 9, c === 0 ? MUTED : INK, false);
      trow.getCell(c).setAttributes(attr);
    }
  }

  body.appendParagraph('').setSpacingAfter(14).setFontSize(1);

  var remark = body.appendParagraph('All observed values are within the specified tolerance. Material conforms to the above specification.');
  remark.setFontFamily(BODY).setFontSize(8.5).setForegroundColor(INK).setSpacingAfter(14);

  var note = body.appendParagraph('This is a computer generated report. No signature is required.');
  note.setFontFamily(BODY).setFontSize(8).setBold(true).setForegroundColor(MUTED)
    .setAlignment(DocumentApp.HorizontalAlignment.CENTER).setSpacingBefore(6);

  var foot = body.appendParagraph(o.reportNo + '  ·  ' + o.item + '  ·  Invoice ' + o.invoiceNo);
  foot.setFontFamily(BODY).setFontSize(7).setForegroundColor(MUTED)
    .setAlignment(DocumentApp.HorizontalAlignment.CENTER).setSpacingBefore(4);

}

/**
 * Build ONE PDF holding every report for an invoice, one page each.
 * Returns { id, url } for the single stored file.
 */
function trBuildCombinedPdf_(pages, meta) {
  var doc = DocumentApp.create('TEST REPORT ' + String(meta.invoiceNo).replace(/[\/\\]/g, '-') +
    ' - ' + new Date().getTime());
  var body = doc.getBody();
  body.setPageWidth(595).setPageHeight(842);       // A4 in points
  body.setMarginTop(30).setMarginBottom(30).setMarginLeft(34).setMarginRight(34);
  var W = 595 - 34 - 34;                            // 527pt usable

  pages.forEach(function (o, idx) {
    trRenderReportPage_(body, o, W);
    if (idx < pages.length - 1) body.appendPageBreak();
  });

  doc.saveAndClose();
  var pdfName = 'TEST REPORT ' + String(meta.invoiceNo).replace(/[\/\\]/g, '-') + '.pdf';
  var blob = DriveApp.getFileById(doc.getId()).getAs('application/pdf').setName(pdfName);
  var file = meta.folder.createFile(blob);
  if (TR_LINK_SHARE_) file.setSharing(DriveApp.Access.ANYONE_WITH_LINK, DriveApp.Permission.VIEW);
  DriveApp.getFileById(doc.getId()).setTrashed(true);   // the intermediate Doc is not a record
  return { id: file.getId(), url: file.getUrl() };
}

/**
 * Look up the PO number for a product code from Dispatch, by header name.
 * Returns '' when the code is not on the board — the report still prints, with the field blank,
 * rather than failing over a value that is informational.
 */
function trPoNumbersByCode_(dispatch) {
  // Built ONCE for the whole run and returned as a lookup. This was previously a per-product
  // helper that re-read every row of Dispatch on each call — for a 4-product invoice that is
  // four full-sheet reads to fetch four values.
  var map = {};
  var labelRow = findInvoiceRow_(dispatch) + 1;
  var lastCol = dispatch.getLastColumn();
  var headers = dispatch.getRange(labelRow, 1, 1, lastCol).getValues()[0];
  var iCode = headers.indexOf('Code'), iPo = headers.indexOf('PO Number');
  if (iCode === -1 || iPo === -1) return map;
  var last = dispatch.getLastRow();
  if (last <= labelRow) return map;
  var rows = dispatch.getRange(labelRow + 1, 1, last - labelRow, lastCol).getValues();
  for (var i = 0; i < rows.length; i++) {
    var key = String(rows[i][iCode]).trim();
    // First occurrence wins, matching the old sequential-scan behaviour.
    if (key && !(key in map)) map[key] = rows[i][iPo] || '';
  }
  return map;
}
