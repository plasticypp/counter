/**
 * TEST REPORT — one report per product, generated from an invoice column.
 *
 * Distinct from the existing SPEC print (generateSpecPdfForInvoice_), which is left untouched:
 *   - "TEST REPORT" centred under a YPP letterhead, not a "CERTIFICATE OF QUALITY" banner.
 *   - Invoice number AND PO number in the header.
 *   - A real report number from the TestReports register sheet, allocated under LockService,
 *     so two people printing at once cannot receive the same number.
 *   - ONE PDF per invoice, a page per product, filed in "Test Reports/<FY>/".
 *   - 5 observations per characteristic, symmetric about nominal and hard-clamped inside
 *     tolerance — an observation outside spec on a document that declares PASS would be a
 *     contradiction the reader is entitled to trust us not to print.
 *   - "This is a computer generated report. No signature is required."
 *
 * ASSUMPTIONS (never explicitly confirmed — say the word and either is a one-line change):
 *   - Sample size 5. The old SPEC template used 4.
 *   - PDFs are link-shareable (anyone with the link can view), so the link can be sent to a
 *     customer without a Drive permission request.
 */

